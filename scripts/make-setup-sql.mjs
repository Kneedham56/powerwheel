/**
 * Builds supabase/new-user-setup.sql: every migration in order, in one file you can paste into
 * the Supabase SQL editor, with Kyle's seed data (accounts Individual/Joint, the Tesla CC stream)
 * swapped for a neutral starter account and stream.
 *
 *   npm run setup:sql
 *
 * Re-run it whenever a new migration is added, and commit the result.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

/** 0001 ends with a seed section; keep everything before it. */
function withoutSeed(sql) {
  const at = sql.indexOf("-- seed");
  if (at < 0) throw new Error("couldn't find the seed section in 0001 (did its layout change?)");
  return sql.slice(0, sql.lastIndexOf("-- ---", at)).trimEnd() + "\n";
}

const starter = `-- ---------------------------------------------------------------------------
-- starter data: one account, one stream, and a rule sending everything to it.
-- Rename them (or add more) on the app's Settings page, or pick others on the Import page.
-- ---------------------------------------------------------------------------

insert into accounts (name) values ('My Account');

insert into streams (name, slug, description, color, sort_order) values
  ('Wheel', 'wheel', 'All my trades', '#2a78d6', 1);

insert into stream_rules (stream_id, account_id, ticker, kind, priority)
select s.id, a.id, null, null, 100
from streams s, accounts a
where s.slug = 'wheel' and a.name = 'My Account';
`;

const parts = files.map((f, i) => {
  const sql = readFileSync(`${dir}/${f}`, "utf8");
  return `-- ===== ${f} =====\n${i === 0 ? withoutSeed(sql) : sql.trimEnd() + "\n"}`;
});

const out = `-- PowerWheel: database setup for a new person.
-- Generated by \`npm run setup:sql\` from supabase/migrations. Do not edit by hand.
-- Paste this whole file into the Supabase SQL editor (SQL Editor -> New query) and click Run, once.

${parts.join("\n")}
${starter}`;

writeFileSync("supabase/new-user-setup.sql", out);
console.log(`wrote supabase/new-user-setup.sql from ${files.join(", ")}`);
